#!/usr/bin/env python3
"""Build the README recipe gallery from recipes.yaml.

The table is written between the markers below. ``--check`` exits 1 when the
README is out of date (used by CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from lab.recipe import CATEGORIES, discover, load_index  # noqa: E402

START = "<!-- recipes:start -->"
END = "<!-- recipes:end -->"
STATUS_LABEL = {"ready": "ready", "beta": "beta", "planned": "planned", "n/a": "n/a"}


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(entries: list[dict]) -> str:
    order = {name: i for i, name in enumerate(CATEGORIES)}
    entries = sorted(entries, key=lambda e: (order.get(e["category"], 99), e["name"]))
    lines = [
        f"{len(entries)} recipes. Generated from `recipes.yaml` by `scripts/gen_index.py`; do not edit by hand.",
        "",
        "| Recipe | Category | Summary | Risk | Linux | macOS |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for e in entries:
        variants = e.get("variants") or {}
        lines.append(
            f"| [{_cell(e['name'])}]({e['path']}/RECIPE.md) | {_cell(e['category'])} | {_cell(e['summary'])} | {_cell(e['risk'])} "
            f"| {STATUS_LABEL.get(variants.get('linux'), '?')} | {STATUS_LABEL.get(variants.get('macos'), '?')} |"
        )
    return "\n".join(lines)


HEADER = (
    "# Index source for the README gallery (scripts/gen_index.py).\n"
    "# Generated from each RECIPE.md by: python3 scripts/gen_index.py --sync\n"
    "# Recipe pull requests do not edit this file.\n"
)


def sync_index(root: Path) -> str:
    """Build the recipes.yaml text from every RECIPE.md under ``root/recipes``."""
    order = {name: i for i, name in enumerate(CATEGORIES)}
    recipes = sorted(discover(root / "recipes"), key=lambda r: (order.get(r.category, 99), r.name))
    if not recipes:
        return HEADER + "recipes: []\n"
    lines = [HEADER + "recipes:"]
    for r in recipes:
        v = r.meta.get("variants") or {}
        lines += [
            f"  - path: recipes/{r.id}",
            f"    name: {r.meta['name']}",
            f"    category: {r.meta['category']}",
            f"    summary: {json.dumps(r.meta['summary'], ensure_ascii=False)}",
            f"    risk: {r.meta['risk']}",
            f"    status: {r.meta['status']}",
            f"    variants: {{linux: {v.get('linux')}, macos: {v.get('macos')}}}",
        ]
    return "\n".join(lines) + "\n"


def splice(readme: str, table: str) -> str | None:
    """Return the README with the table between the markers, or None without markers."""
    if START not in readme or END not in readme:
        return None
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{table}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the README gallery is out of date")
    parser.add_argument("--stdout", action="store_true", help="print the table instead of editing the README")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    parser.add_argument("--index", type=Path, default=ROOT / "recipes.yaml")
    parser.add_argument("--sync", action="store_true", help="rewrite recipes.yaml from every RECIPE.md, then update the README")
    args = parser.parse_args(argv)

    if args.sync:
        text = sync_index(args.index.parent)
        if args.check:
            if args.index.read_text(encoding="utf-8") != text:
                print("gen_index: recipes.yaml is out of date; run: python3 scripts/gen_index.py --sync", file=sys.stderr)
                return 1
        else:
            args.index.write_text(text, encoding="utf-8")
            print(f"gen_index: synced {args.index.name}")

    entries = load_index(args.index)
    if not entries and not args.stdout:
        # A branch that carries no indexed recipe yet keeps the README placeholder.
        print("gen_index: recipes.yaml lists no recipe; README left unchanged")
        return 0
    table = render(entries)
    if args.stdout:
        print(table)
        return 0
    readme = args.readme.read_text(encoding="utf-8")
    updated = splice(readme, table)
    if updated is None:
        print(f"gen_index: markers {START} / {END} not found in {args.readme.name}; nothing to do", file=sys.stderr)
        return 0
    if updated == readme:
        print("gen_index: README gallery is up to date")
        return 0
    if args.check:
        print("gen_index: README gallery is out of date; run: python3 scripts/gen_index.py", file=sys.stderr)
        return 1
    args.readme.write_text(updated, encoding="utf-8")
    print(f"gen_index: updated {args.readme.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
